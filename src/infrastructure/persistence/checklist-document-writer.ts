import { lstat, rename, writeFile, rm } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import path from 'node:path';
import type { TaskService } from '../../application/task-service.js';
import type { WorkspaceGuard } from '../security/workspace-guard.js';

const markdownCell = (value: string): string => value.replace(/\|/g, '\\|').replace(/[\r\n]+/g, ' ').trim();

export class ChecklistDocumentWriter {
  constructor(private readonly tasks: TaskService, private readonly guard: WorkspaceGuard) {}

  async write(planId: string): Promise<string> {
    const snapshot = await this.tasks.getPlan(planId);
    const directory = await this.guard.ensureEvidenceDirectory('.harness/checklists');
    const target = path.join(directory, `${planId}.md`);
    const evidence = await this.tasks.getEvidenceForPlan(planId);

    try {
      const existing = await lstat(target);
      if (existing.isSymbolicLink() || !existing.isFile()) throw new Error('Generated checklist target must be a regular file, not a symlink or directory.');
    } catch (error) {
      if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
    }

    const lines = [
      `# Verification Checklist: ${markdownCell(snapshot.plan.title)}`,
      '',
      `- Plan ID: \`${snapshot.plan.id}\``,
      `- Updated: ${new Date().toISOString()}`,
      `- Request: ${markdownCell(snapshot.plan.request)}`,
      `- Repair iterations: ${snapshot.plan.repairIterations}/${snapshot.plan.maxRepairIterations}`,
      '',
      '## Execution tasks',
      '',
      '| Task | Role | Status | Evidence | Failure / Block reason |',
      '|---|---|---|---|---|'
    ];

    for (const task of snapshot.tasks) {
      const evidenceIds = task.evidenceIds.map(id => `\`${id}\``).join(', ') || 'None';
      lines.push(`| ${markdownCell(task.title)} | ${markdownCell(task.ownerRole)} | ${task.status.toUpperCase()} | ${evidenceIds} | ${markdownCell(task.failureReason ?? '')} |`);
    }

    lines.push('', '## Quality checkpoints', '', '| Quality dimension | Required | Status | Evidence IDs | Reason |', '|---|---:|---|---|---|');
    for (const item of snapshot.checkpoints) {
      const evidenceIds = item.evidenceIds.map(id => `\`${id}\``).join(', ') || 'None';
      lines.push(`| ${markdownCell(item.title)} | ${item.required ? 'Yes' : 'No'} | ${item.status.toUpperCase()} | ${evidenceIds} | ${markdownCell(item.reason ?? '')} |`);
    }

    lines.push('', '## Evidence register', '', '| Evidence ID | Kind | Title | Path / URI | Created by |', '|---|---|---|---|---|');
    if (evidence.length === 0) lines.push('| None | | No evidence recorded | | |');
    for (const item of evidence) {
      const location = item.path ?? item.uri ?? 'Not linked';
      lines.push(`| \`${item.id}\` | ${item.kind} | ${markdownCell(item.title)} | ${markdownCell(location)} | ${markdownCell(item.createdBy)} |`);
    }
    lines.push('', 'This document is generated by the MCP harness. Do not edit manually. Update task and checkpoint states through MCP tools.', '');

    const temporary = `${target}.${process.pid}.${randomUUID()}.tmp`;
    try {
      await writeFile(temporary, lines.join('\n'), { encoding: 'utf8', flag: 'wx', mode: 0o600 });
      await rename(temporary, target);
    } catch (error) {
      await rm(temporary, { force: true }).catch(() => undefined);
      throw error;
    }

    return path.relative(this.guard.root, target);
  }
}
